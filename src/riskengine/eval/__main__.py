"""Score the configured models on the public test sets and write docs/RESULTS.md.

uv run python -m riskengine.eval
"""

import json
import resource
import time
from collections.abc import Callable, Sequence

import pandas as pd
from sklearn.metrics import accuracy_score, classification_report, f1_score

from riskengine.config import load_config
from riskengine.eval.datasets import EVENT_TEST_CLASSES, tfns_test, topic_test
from riskengine.nlp.events import classify_keywords
from riskengine.nlp.sentiment import FinBert
from riskengine.paths import DATA, ROOT

RESULTS_MD = ROOT / "docs" / "RESULTS.md"
RESULTS_JSON = DATA / "outputs" / "eval_results.json"


def peak_rss_mb() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024  # Linux reports KB


def model_size_mb(model) -> float:
    """Weights in memory (parameters x bytes each), independent of what the disk cache holds."""
    return sum(p.numel() * p.element_size() for p in model.parameters()) / 1e6


def timed(predict: Callable[[Sequence[str]], list[str]], texts: list[str]) -> tuple[list, float]:
    predict(texts[:64])  # warm-up batch (DECISIONS E4)
    t0 = time.perf_counter()
    out = predict(texts)
    return out, len(texts) / (time.perf_counter() - t0)


def evaluate(name, test, predict, classes, size_mb) -> dict:
    pred, speed = timed(predict, test["text"].tolist())
    report = classification_report(
        test["label"], pred, labels=classes, output_dict=True, zero_division=0
    )
    return {
        "model": name,
        "n": len(test),
        "accuracy": accuracy_score(test["label"], pred),
        "macro_f1": f1_score(test["label"], pred, labels=classes, average="macro", zero_division=0),
        "per_class_f1": {c: report[c]["f1-score"] for c in classes},
        "texts_per_s": speed,
        "model_size_mb": size_mb,
        "peak_rss_mb": peak_rss_mb(),
    }


def to_markdown(results: dict) -> str:
    lines = ["# Results", "", "Generated by `uv run python -m riskengine.eval`. "
             "Test rules: [DECISIONS.md](DECISIONS.md). CPU only.", ""]  # fmt: skip
    for task, rows in results.items():
        lines += [f"## {task}", ""]
        df = pd.DataFrame(rows)
        table = df[["model", "n", "accuracy", "macro_f1", "texts_per_s", "model_size_mb"]]
        lines += [table.round(3).to_markdown(index=False), ""]
        per_class = pd.DataFrame({r["model"]: r["per_class_f1"] for r in rows}).round(3)
        lines += ["Per-class F1:", "", per_class.to_markdown(), ""]
    return "\n".join(lines)


def main() -> None:
    config = load_config()
    results: dict[str, list[dict]] = {"Sentiment (TFNS, 3 classes)": [], "Events (TFN-topic)": []}

    events = topic_test()
    results["Events (TFN-topic)"].append(
        evaluate(
            config.events,
            events,
            lambda ts: [classify_keywords(t) for t in ts],
            EVENT_TEST_CLASSES,
            0.0,
        )
    )

    finbert = FinBert()
    results["Sentiment (TFNS, 3 classes)"].append(
        evaluate(
            "finbert",
            tfns_test(),
            finbert.classify,
            ["negative", "neutral", "positive"],
            model_size_mb(finbert.model),
        )
    )

    RESULTS_JSON.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(results, indent=2))
    RESULTS_MD.write_text(to_markdown(results))
    print(to_markdown(results))


if __name__ == "__main__":
    main()
